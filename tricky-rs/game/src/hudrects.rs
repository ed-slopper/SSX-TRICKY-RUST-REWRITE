/// `SpriteSet_InitHudGameRects` 0x1f4440 (a0 the set)
pub fn init_hud_game_rects(m: &mut Mem, set: u32) {
    for (k, (_, f)) in HUD_GAME_RECTS.iter().enumerate() {
        let at = set + 8 + 0x1c * k as u32;
        m.w32(at, u32::MAX);
        for (i, v) in f.iter().enumerate() {
            m.w32(at + 4 + 4 * i as u32, *v);
        }
    }
}

/// `SpriteSet_BindHudGameTex` 0x1f9080 (a0 the set, a1 the `.ssh`): each of the three shapes the file has
/// (`Shape_FindByName` 0x2c2528) made a texture by the renderer (gApp+0x724, its virtual +0x154(shape, name, 0)) into
/// its field; then every record's texture from those fields (a field whose shape is missing keeps its word).
/// `texture(k)` is the renderer's answer for shape k of [`SHAPES`], None when the file has no such shape.
pub fn bind_hud_game_tex(m: &mut Mem, set: u32, texture: &mut dyn FnMut(usize) -> Option<u32>) {
    for (k, field) in TEXTURES.iter().enumerate() {
        if let Some(t) = texture(k) {
            m.w32(set + field, t);
        }
    }
    let tex: [u32; 3] = std::array::from_fn(|k| m.r32(set + TEXTURES[k]));
    for (k, (t, _)) in HUD_GAME_RECTS.iter().enumerate() {
        m.w32(set + 8 + 0x1c * k as u32, tex[*t as usize]);
    }
}
